def build_style_block(include_fewshot: bool = True, n_fewshot: int = 3,
                      valence: str = None) -> str:
    """기사 생성 프롬프트에 주입할 스타일 블록 생성.

    valence: 'BAD'면 구조조정·전환 톤 예시(GS리테일)를 앞세움.
             'GOOD'면 수주·성장 톤(디아이) 앞세움. None이면 기본 순서.
    """
    parts = [FINSCOPE_PERSONA, "", GONGJONG_MIN_SIGNATURE]
    if include_fewshot and GONGJONG_MIN_FEWSHOT:
        samples = list(GONGJONG_MIN_FEWSHOT)
        # valence에 맞는 예시를 앞쪽으로 — 적자/전환 단서엔 GS리테일류, 성장엔 디아이류
        if valence == "GOOD":
            samples = [samples[1]] + [s for i, s in enumerate(samples) if i != 1]
        # (BAD/None은 기본 순서 — GS리테일이 이미 0번)
        parts.append("\n[고종민 기자 실제 기사 예시 — 이 톤·구조를 그대로 따를 것]")
        for i, ex in enumerate(samples[:n_fewshot], 1):
            parts.append(
                f"\n예시{i}\n제목: {ex['headline']}\n"
                f"부제: {ex['sub']}\n리드: {ex['lead']}"
            )
    return "\n".join(parts)


